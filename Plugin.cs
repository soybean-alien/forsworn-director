[BepInPlugin(PluginId, PluginName, PluginVersion)]
public sealed class Plugin : BasePlugin
{
    public const string PluginId = "soybean_alien.forsworn.director";
    public const string PluginName = "Forsworn Director";
    public const string PluginVersion = "1.0.0";
    private const string LegacyConfigName = "net.codex.forsworn.director.cfg";

    internal const int CurrencyReserve = 999_999;
    internal const int TalentReserve = 999_999;
    internal static readonly int[] XpPresets = { 2, 10, 100, 1000, 5000 };

    internal static Plugin Instance;
    internal static ConfigEntry<bool> MasterEnabled;
    internal static ConfigEntry<KeyCode> ToggleKey;
    internal static ConfigEntry<float> PanelX;
    internal static ConfigEntry<float> PanelY;
    internal static ConfigEntry<bool> InfiniteGold;
    internal static ConfigEntry<bool> InfiniteSoulShards;
    internal static ConfigEntry<bool> InfiniteUpgradeTokens;
    internal static ConfigEntry<bool> UnlimitedTalentPoints;
    internal static ConfigEntry<bool> MegaBattleXP;
    internal static ConfigEntry<int> BattleXPMultiplier;
    internal static readonly Dictionary<string, ClassSettings> Classes = new(StringComparer.OrdinalIgnoreCase);

    private Harmony _harmony;

    public override void Load()
    {
        Instance = this;
        MigrateLegacyConfig();

        MasterEnabled = Config.Bind("General", "Enabled", true, "Master switch for all Forsworn Director effects.");
        ToggleKey = Config.Bind("General", "ToggleKey", KeyCode.F8, "Key that shows or hides the Director panel.");
        PanelX = Config.Bind("General", "PanelX", 28f, "Panel position from the left edge (reference pixels at 1920x1080). Drag the title bar to change it.");
        PanelY = Config.Bind("General", "PanelY", 28f, "Panel position from the top edge (reference pixels at 1920x1080).");
        InfiniteGold = Config.Bind("Resources", "UnlimitedGold", false, "Keep local run gold at a safe high value. Solo/offline only.");
        InfiniteSoulShards = Config.Bind("Resources", "UnlimitedSoulShards", false, "Keep local run Soul Shards at a safe high value. This is local in-game currency.");
        InfiniteUpgradeTokens = Config.Bind("Resources", "UnlimitedUpgradeTokens", false, "Keep every hero's Upgrade Tokens at 999,999. Solo/offline only.");
        UnlimitedTalentPoints = Config.Bind("Progression", "UnlimitedTalentPoints", false, "Allow talent nodes to be purchased without spending the available point count. Node rank limits remain enforced by the game.");
        MegaBattleXP = Config.Bind("Progression", "MegaBattleXP", false, "Multiply progression XP when the game awards it. XP is never generated by this mod while idle.");
        BattleXPMultiplier = Config.Bind("Progression", "BattleXPMultiplier", 10, "Multiplier applied to XP awards. Values are clamped to 2 through 5000.");

        foreach (var className in Enum.GetNames(typeof(HeroClassRegistry.Name)).OrderBy(name => name, StringComparer.OrdinalIgnoreCase))
        {
            if (string.Equals(className, "None", StringComparison.OrdinalIgnoreCase))
                continue;

            Classes[className] = new ClassSettings(Config, className);
        }

        _harmony = new Harmony(PluginId);
        InstallPatches();
        ClassInjector.RegisterTypeInIl2Cpp<DirectorPanel>();
        AddComponent<DirectorPanel>();
        Log.LogInfo($"{PluginName} {PluginVersion} loaded. {Classes.Count} class profiles; press {ToggleKey.Value} in game. Effects pause outside solo/offline play.");
    }

    // v0.1.x shipped under Codex's GUID; carry the user's saved choices over once.
    private void MigrateLegacyConfig()
    {
        try
        {
            var legacy = Path.Combine(Paths.ConfigPath, LegacyConfigName);
            if (!File.Exists(legacy))
                return;

            var current = Config.ConfigFilePath;
            if (File.Exists(current) && File.ReadAllText(current).Contains("[General]"))
                return;

            File.Copy(legacy, current, true);
            Config.Reload();
            File.Move(legacy, legacy + ".migrated");
            Log.LogInfo($"Migrated settings from {LegacyConfigName}.");
        }
        catch (Exception exception)
        {
            Log.LogWarning($"Could not migrate legacy settings: {exception.Message}");
        }
    }

    internal static int XpMultiplier => Math.Max(2, Math.Min(5000, BattleXPMultiplier.Value));

    // Cached once per frame by the panel component. The stat hooks fire very often in battle
    // (AI move evaluation), and re-running the FishNet session check per call made fights sluggish.
    internal static bool EffectsEnabled { get; private set; }

    internal static void RefreshSession() => EffectsEnabled = MasterEnabled != null && MasterEnabled.Value && IsSoloSession();

    internal static bool IsSoloSession() => TryGetSoloSession(out _);

    internal static bool TryGetSoloSession(out string status)
    {
        try
        {
            if (InstanceFinder.IsOffline)
            {
                status = "Offline play";
                return true;
            }

            if (!InstanceFinder.IsHostStarted)
            {
                status = "Waiting for a solo host";
                return false;
            }

            var server = InstanceFinder.ServerManager;
            var clientManager = InstanceFinder.ClientManager;
            var localConnection = clientManager != null ? clientManager.Connection : null;
            if (server == null || server.Clients == null || localConnection == null)
            {
                status = "Host connection unconfirmed";
                return false;
            }

            // FishNet counts the local host client in ServerManager.Clients.
            var localClientRegistered = server.Clients.ContainsKey(localConnection.ClientId);
            var remoteClients = server.Clients.Count - (localClientRegistered ? 1 : 0);
            if (localClientRegistered && remoteClients == 0)
            {
                status = "Solo host";
                return true;
            }

            status = remoteClients > 0 ? $"Co-op: {remoteClients} other player(s)" : "Waiting for local host";
            return false;
        }
        catch
        {
            status = "Session unreadable";
            return false;
        }
    }

    internal static void SaveConfig()
    {
        Instance.Config.Save();
        ApplyLoadedHeroes();
    }

    internal static ClassSettings For(CharacterClass characterClass)
    {
        if (characterClass == null || !characterClass.IsHero())
            return null;

        return Classes.TryGetValue(characterClass.heroClassName.ToString(), out var settings) ? settings : null;
    }

    internal static void ApplyStats(MechanicStats stats, CharacterClass owner = null)
    {
        if (!EffectsEnabled || stats == null || owner == null)
            return;

        // Use the class passed by the caller. Reading stats.characterClass here can race
        // IL2CPP scene initialization, before that native field is safe to dereference.
        var entry = Register(stats, owner);
        if (entry == null)
            return;

        var settings = entry.Settings;
        if (settings.MaxHealth.Value)
            stats.currentHP = stats.maxHP;
        if (settings.MaxActionPoints.Value)
            stats.SetRemainingAP(entry.MaxActionPoints);
        if (settings.MaxMovement.Value)
            stats.SetRemainingMovement(entry.MaxMoveDistance, true);
        if (settings.MaxUltimate.Value)
            stats.currentUltimateCharge = stats.maxUltimateCharge;
    }

    // Hero registry, keyed by the native MechanicStats pointer. The stat hooks run while FishNet
    // is still loading scenes, when MechanicStats.characterClass can point at an object that isn't
    // readable yet (AccessViolation in get_characterClass, Act 1 transition). So hooks never touch
    // characterClass: heroes are resolved here at safe moments (round setup, the 0.5 s tick, panel
    // actions) and the hooks only look up their own pointer.
    private sealed class HeroEntry
    {
        internal ClassSettings Settings;
        internal int MaxActionPoints;
        internal float MaxMoveDistance;
    }

    private static readonly Dictionary<IntPtr, HeroEntry> HeroesByStats = new();

    private static HeroEntry Register(MechanicStats stats, CharacterClass owner)
    {
        var pointer = stats != null ? stats.Pointer : IntPtr.Zero;
        if (pointer == IntPtr.Zero)
            return null;

        var settings = For(owner);
        if (settings == null)
        {
            HeroesByStats.Remove(pointer);
            return null;
        }

        var entry = new HeroEntry { Settings = settings, MaxActionPoints = stats.maxActionPoints, MaxMoveDistance = stats.maxMoveDistance };
        HeroesByStats[pointer] = entry;
        return entry;
    }

    private static ClassSettings Lookup(MechanicStats stats, out HeroEntry entry)
    {
        entry = null;
        return EffectsEnabled && stats != null && HeroesByStats.TryGetValue(stats.Pointer, out entry) ? entry.Settings : null;
    }

    private static ClassSettings Lookup(MechanicStats stats) => Lookup(stats, out _);

    // Rebuilt from scratch so pointers of destroyed heroes can't be inherited by new objects for long.
    // Heroes found by the last tick: one scene scan shared by the registry, boosts, tokens and readout.
    internal static readonly List<CoreCharacter> Heroes = new();

    private static void RefreshHeroRegistry()
    {
        HeroesByStats.Clear();
        Heroes.Clear();
        try
        {
            foreach (var character in UnityEngine.Object.FindObjectsOfType<CoreCharacter>())
            {
                if (character != null && Register(character.mechanicStats, character.characterClass) != null)
                    Heroes.Add(character);
            }
        }
        catch (Exception exception)
        {
            Instance?.Log.LogWarning($"Could not refresh hero registry: {exception.Message}");
        }
    }

    // Called a few times a second by the panel component, open or not.
    internal static void Tick()
    {
        RefreshHeroRegistry();
        Boosts.Tick();
        UpgradeTokens.Tick();
    }

    internal static void ApplyLoadedHeroes()
    {
        RefreshSession();
        Tick();
        if (!EffectsEnabled)
            return;

        try
        {
            foreach (var character in Heroes)
            {
                if (character != null)
                    ApplyStats(character.mechanicStats, character.characterClass);
            }
        }
        catch (Exception exception)
        {
            Instance?.Log.LogWarning($"Could not refresh active hero stats: {exception.Message}");
        }
    }

    internal static CoreCharacter FindHero(string className)
    {
        try
        {
            foreach (var character in Heroes)
            {
                var characterClass = character != null ? character.characterClass : null;
                if (characterClass != null && characterClass.IsHero()
                    && string.Equals(characterClass.heroClassName.ToString(), className, StringComparison.OrdinalIgnoreCase))
                    return character;
            }
        }
        catch
        {
            // Scene transitions can destroy characters mid-scan; the readout simply shows nothing.
        }

        return null;
    }

    private void InstallPatches()
    {
        Patch(typeof(MechanicStats), "SetupRemainingStats", postfix: nameof(AfterSetupRemainingStats));
        Patch(typeof(MechanicStats), "ReceiveDamage", prefix: nameof(BeforeReceiveDamage), postfix: nameof(AfterReceiveDamage));
        Patch(typeof(MechanicStats), "ReceiveEventDamage", prefix: nameof(BeforeReceiveEventDamage), postfix: nameof(AfterReceiveEventDamage));
        Patch(typeof(MechanicStats), "SetDeathStats", prefix: nameof(BeforeSetDeathStats));
        Patch(typeof(MechanicStats), "SetRemainingAP", prefix: nameof(BeforeSetRemainingAP));
        Patch(typeof(MechanicStats), "SetRemainingMovement", prefix: nameof(BeforeSetRemainingMovement));
        Patch(typeof(MechanicStats), "ConsumeUltimateCharges", prefix: nameof(BeforeConsumeUltimate));

        PatchConstructors(typeof(InventoryData), nameof(AfterInventoryDataCreated));
        Patch(typeof(InventoryData), "ApplyResources", postfix: nameof(AfterApplyResources));
        Patch(typeof(InventoryData), "PlayerGold", prefix: nameof(BeforePlayerGold));
        Patch(typeof(InventoryData), "PartyGoldTotal", prefix: nameof(BeforePartyGold));
        Patch(typeof(InventoryData), "PartyGoldForPlayer", prefix: nameof(BeforePlayerGold));
        Patch(typeof(InventoryData), "PartySoulShardsTotal", prefix: nameof(BeforePartySoulShards));

        PatchConstructors(typeof(TalentTreeService), nameof(AfterTalentTreeCreated));
        Patch(typeof(TalentTreeService), "UpgradeTalent", prefix: nameof(BeforeTalentUpgrade), postfix: nameof(AfterTalentUpgrade));
        Patch(typeof(TalentTreeService), "DowngradeTalent", postfix: nameof(AfterTalentUpgrade));

        // PlayerProgressionData.AddExperiencePoints(owner, amount) feeds HeroProgressionData, so patch only this one.
        Patch(typeof(PlayerProgressionData), "AddExperiencePoints", prefix: nameof(BeforeExperienceAward));

        Patch(typeof(AbilityCraftingService), "get_currentUpgradeTokens", prefix: nameof(BeforeCurrentUpgradeTokens));

        // Clicks on the panel must not walk the party or pick combat targets underneath it.
        Patch(typeof(FreeRoamSystem), "MoveToWaypoint", prefix: nameof(BeforeWorldClick));
        Patch(typeof(CoreActionSystem), "HandleAbilityDecisionMade", prefix: nameof(BeforeAbilityDecision));
        // On the act map, clicks would otherwise paint or erase map markings under the panel.
        Patch(typeof(MapMarkerController), "BeginDraw", prefix: nameof(BeforeWorldClick));
        Patch(typeof(MapMarkerController), "BeginErase", prefix: nameof(BeforeWorldClick));
    }

    public static bool BeforeCurrentUpgradeTokens(ref int __result)
    {
        if (!EffectsEnabled || !InfiniteUpgradeTokens.Value)
            return true;

        __result = CurrencyReserve;
        return false;
    }

    public static bool BeforeWorldClick() => !DirectorPanel.PointerCaptured;

    public static bool BeforeAbilityDecision(ref bool __result)
    {
        if (!DirectorPanel.PointerCaptured)
            return true;

        __result = false;
        return false;
    }

    private void Patch(Type type, string name, string prefix = null, string postfix = null)
    {
        var target = AccessTools.Method(type, name);
        if (target == null)
        {
            Log.LogWarning($"Could not locate {type.Name}.{name}; that feature will be unavailable.");
            return;
        }

        var prefixMethod = prefix == null ? null : AccessTools.Method(typeof(Plugin), prefix);
        var postfixMethod = postfix == null ? null : AccessTools.Method(typeof(Plugin), postfix);
        _harmony.Patch(
            target,
            prefix: prefixMethod == null ? null : new HarmonyMethod(prefixMethod),
            postfix: postfixMethod == null ? null : new HarmonyMethod(postfixMethod));
    }

    private void PatchConstructors(Type type, string postfix)
    {
        var postfixMethod = AccessTools.Method(typeof(Plugin), postfix);
        foreach (var constructor in type.GetConstructors(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic))
            _harmony.Patch(constructor, postfix: new HarmonyMethod(postfixMethod));
    }

    public static void AfterSetupRemainingStats(MechanicStats __instance, CharacterClass characterClass)
    {
        ApplyStats(__instance, characterClass);
    }

    public static bool BeforeReceiveDamage(MechanicStats __instance, ref bool __result)
    {
        var settings = Lookup(__instance);
        if (settings == null || !settings.GodMode.Value)
            return true;

        if (__instance.maxHP > 0)
            __instance.currentHP = __instance.maxHP;
        __result = false;
        return false;
    }

    public static void AfterReceiveDamage(MechanicStats __instance, ref bool __result)
    {
        var settings = Lookup(__instance);
        if (settings == null || (!settings.GodMode.Value && !settings.MaxHealth.Value))
            return;

        __instance.currentHP = __instance.maxHP;
        if (settings.GodMode.Value)
            __result = false;
    }

    public static bool BeforeReceiveEventDamage(MechanicStats __instance)
    {
        var settings = Lookup(__instance);
        return settings == null || !settings.GodMode.Value;
    }

    public static void AfterReceiveEventDamage(MechanicStats __instance)
    {
        var settings = Lookup(__instance);
        if (settings != null && (settings.GodMode.Value || settings.MaxHealth.Value))
            __instance.currentHP = __instance.maxHP;
    }

    public static bool BeforeSetDeathStats(MechanicStats __instance)
    {
        var settings = Lookup(__instance);
        return settings == null || (!settings.GodMode.Value && !settings.MaxHealth.Value);
    }

    public static void BeforeSetRemainingAP(MechanicStats __instance, ref int amount)
    {
        // Runs during scene loading: use the limit cached by Register, never native fields.
        var settings = Lookup(__instance, out var entry);
        if (settings != null && settings.MaxActionPoints.Value)
            amount = entry.MaxActionPoints;
    }

    public static void BeforeSetRemainingMovement(MechanicStats __instance, ref float amount)
    {
        var settings = Lookup(__instance, out var entry);
        if (settings != null && settings.MaxMovement.Value)
            amount = entry.MaxMoveDistance;
    }

    public static void BeforeConsumeUltimate(MechanicStats __instance, ref int percentage)
    {
        var settings = Lookup(__instance);
        if (settings != null && settings.MaxUltimate.Value)
            percentage = 0;
    }

    public static void AfterInventoryDataCreated(InventoryData __instance) => TopUpCurrencies(__instance);

    public static void AfterApplyResources(InventoryData __instance) => TopUpCurrencies(__instance);

    public static bool BeforePlayerGold(InventoryData __instance, ref int __result)
    {
        if (!EffectsEnabled || !InfiniteGold.Value)
            return true;

        TopUpCurrencies(__instance);
        __result = CurrencyReserve;
        return false;
    }

    public static bool BeforePartyGold(InventoryData __instance, ref int __result) => BeforePlayerGold(__instance, ref __result);

    public static bool BeforePartySoulShards(InventoryData __instance, ref int __result)
    {
        if (!EffectsEnabled || !InfiniteSoulShards.Value)
            return true;

        TopUpCurrencies(__instance);
        __result = CurrencyReserve;
        return false;
    }

    private static void TopUpCurrencies(InventoryData inventory)
    {
        if (!EffectsEnabled || inventory?.personalInventories == null)
            return;

        foreach (var personal in inventory.personalInventories.Values)
        {
            if (personal == null)
                continue;

            if (InfiniteGold.Value)
                personal.gold = CurrencyReserve;
            if (InfiniteSoulShards.Value)
                personal.soulShards = CurrencyReserve;
        }
    }

    public static void AfterTalentTreeCreated(TalentTreeService __instance) => SetTalentPoints(__instance);

    public static void BeforeTalentUpgrade(TalentTreeService __instance) => SetTalentPoints(__instance);

    public static void AfterTalentUpgrade(TalentTreeService __instance) => SetTalentPoints(__instance);

    private static void SetTalentPoints(TalentTreeService service)
    {
        if (EffectsEnabled && UnlimitedTalentPoints.Value && service != null)
            service.availableTalentPoints = TalentReserve;
    }

    public static void BeforeExperienceAward(ref int amount)
    {
        if (!EffectsEnabled || !MegaBattleXP.Value || amount <= 0)
            return;

        amount = (int)Math.Min((long)amount * XpMultiplier, int.MaxValue);
    }
}

internal sealed class ClassSettings
{
    internal readonly string Name;
    internal readonly ConfigEntry<bool> GodMode;
    internal readonly ConfigEntry<bool> MaxHealth;
    internal readonly ConfigEntry<bool> MaxActionPoints;
    internal readonly ConfigEntry<bool> MaxMovement;
    internal readonly ConfigEntry<bool> MaxUltimate;
    internal readonly Dictionary<string, ConfigEntry<bool>> Boosts = new();

    internal ClassSettings(ConfigFile config, string name)
    {
        Name = name;
        var section = "Classes." + name;
        GodMode = config.Bind(section, "GodMode", false, "Prevent player-character death for this class. Solo/offline only.");
        MaxHealth = config.Bind(section, "HealthAtClassMaximum", false, "Keep current HP at this class's current game-calculated maximum.");
        MaxActionPoints = config.Bind(section, "ActionPointsAtClassMaximum", false, "Keep current action points at this class's current game-calculated maximum.");
        MaxMovement = config.Bind(section, "MovementAtClassMaximum", false, "Keep current movement at this class's current game-calculated maximum.");
        MaxUltimate = config.Bind(section, "UltimateAtClassMaximum", false, "Keep ultimate charge full up to this class's current game-calculated maximum.");
        foreach (var (key, label, _) in ForswornDirector.Boosts.Stats)
            Boosts[key] = config.Bind(section, "Boost" + key, false, $"Add +{ForswornDirector.Boosts.Amount} {label} to this class while enabled.");
    }

    internal IEnumerable<ConfigEntry<bool>> All => new[] { GodMode, MaxHealth, MaxActionPoints, MaxMovement, MaxUltimate }.Concat(Boosts.Values);

    internal int ActiveCount => All.Count(entry => entry.Value);
}
